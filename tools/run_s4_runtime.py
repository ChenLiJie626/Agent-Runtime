def analysis_input(sample: dict) -> dict:
    """Allowlist transport: metadata containing labels is never passed onward."""
    return {
        "sample_id": sample["sample_id"], "project_id": sample["project_id"],
        "base_commit": sample["base_commit"], "head_commit": sample["head_commit"],
        "artifacts": [{key: item[key] for key in ("role", "url", "sha256", "size_bytes")} for item in sample["artifacts"]
                      if item["role"] in {"base_source", "head_source"}],
        "paths": list(sample["surface"]["paths"]),
    }


class AuditedExecutor:
    def __init__(self, inner):
        self.inner = inner
        self.calls = []

    def describe_capabilities(self):
        return self.inner.describe_capabilities()

    def run(self, request, tools):
        entry = {"role": request.role, "attempt_id": request.attempt_id,
                 "evidence_reads": [], "status": "running"}
        # Bind the exact prompt generated by the first-party adapter, without
        # storing prompt text or route credentials in the exported run.
        prompt = (self.inner._prompt(request) if isinstance(self.inner, ClaudeAgentExecutor)
                  else canonical_json(to_plain(request)))
        entry["prompt_digest"] = bytes_digest(prompt.encode("utf-8"))
        self.calls.append(entry)

        class Tools:
            query = tools.query
            resolve_evidence_ref = tools.resolve_evidence_ref

            def read_evidence(self, evidence_id):
                raw = tools.read_evidence(evidence_id)
                entry["evidence_reads"].append({"evidence_id": evidence_id,
                                                 "artifact_digest": bytes_digest(raw)})
                return raw

        started = time.monotonic()
        try:
            result = self.inner.run(request, Tools())
            entry.update(status="completed", sdk_session_id=result.sdk_session_id)
            return result
        except Exception as exc:
            entry.update(status="failed", error_type=type(exc).__name__)
            raise
        finally:
            entry["duration_seconds"] = round(time.monotonic() - started, 6)


class QueryBudget:
    """Count actual backend executions; runtime idempotent cache hits are free."""

    def __init__(self, backend, limit):
        self.backend = backend
        self.remaining = limit

    def __getattr__(self, name):
        return getattr(self.backend, name)

    def query(self, request):
        if self.remaining <= 0:
            raise InvalidInput("backend execution budget exhausted")
        self.remaining -= 1
        return self.backend.query(request)


